//! Print a C header containing the exact VMContext/VMStoreContext offsets for
//! the patched WebClient.raknet.wasm, computed by wasmtime-environ 50.0.2's
//! own `VMOffsets` implementation. This is the authoritative way to generate
//! the C++ host's ABI constants; never hand-guess them.
//!
//! Usage: cargo run --offline --release --bin gen_vmctx -- /path/to/module.wasm > vmctx_offsets.h

use anyhow::{Context, Result};
use wasmparser::{Parser, Validator, WasmFeatures};
use wasmtime_environ::{
    BuiltinFunctionIndex, Collector, HostPtr, ModuleEnvironment, ModuleTypesBuilder,
    PtrSize, StaticModuleIndex, Tunables,
};

fn main() -> Result<()> {
    let wasm_path = std::env::args()
        .nth(1)
        .context("usage: gen_vmctx INPUT.wasm")?;
    let wasm = std::fs::read(&wasm_path)
        .with_context(|| format!("failed to read {wasm_path}"))?;

    let mut tunables = Tunables::default_host();
    tunables.collector = Some(Collector::DeferredReferenceCounting);

    let mut features = WasmFeatures::WASM3;
    features |= WasmFeatures::SHARED_EVERYTHING_THREADS;
    features |= WasmFeatures::LEGACY_EXCEPTIONS;
    let mut validator = Validator::new_with_features(features);
    let mut types = ModuleTypesBuilder::new(&validator);
    let mut parser = Parser::new(0);
    parser.set_features(features);

    // Translation only (no codegen): gives us the real module shape so that
    // dynamic VMContext offsets are exact.
    let translation = ModuleEnvironment::new(
        &tunables,
        &mut validator,
        &mut types,
        StaticModuleIndex::from_u32(0),
    )
    .translate(parser, &wasm)
    .map_err(anyhow::Error::from)
    .context("failed to translate wasm module")?;
    let module = &translation.module;

    let vm = wasmtime_environ::VMOffsets::new(HostPtr, module);
    let sc = HostPtr.vm_store_context();
    let fi = HostPtr.vm_function_import();
    let md = HostPtr.vm_memory_definition();
    let td = HostPtr.vm_table_definition();
    let fr = HostPtr.vm_func_ref();

    println!("// @generated by host/gen_vmctx.rs from wasmtime-environ 50.0.2 VMOffsets.");
    println!("// Source of truth: vmctxtypes.rs / vmtypes.rs / vmoffsets.rs / builtin.rs.");
    println!("#pragma once");
    println!();
    println!("#define WASM_PAGE_SIZE 65536u");
    println!("#define VMCTX_NUM_IMPORTED_FUNCTIONS {}u", module.num_imported_funcs);
    println!("#define VMCTX_NUM_IMPORTED_MEMORIES {}u", module.num_imported_memories);
    println!("#define VMCTX_NUM_DEFINED_MEMORIES {}", vm.num_defined_memories);
    println!("#define VMCTX_NUM_OWNED_MEMORIES {}", vm.num_owned_memories);
    println!("#define VMCTX_NUM_IMPORTED_TABLES {}u", module.num_imported_tables);
    println!("#define VMCTX_NUM_DEFINED_TABLES {}", vm.num_defined_tables);
    println!("#define VMCTX_NUM_IMPORTED_GLOBALS {}u", module.num_imported_globals);
    println!("#define VMCTX_NUM_DEFINED_GLOBALS {}", vm.num_defined_globals);
    println!("#define VMCTX_NUM_ESCAPED_FUNCS {}", vm.num_escaped_funcs);
    println!("#define VMCTX_SIZE_OF_VMCTX {}u", vm.size_of_vmctx());
    println!();
    // Static fields of VMContext.
    let stat = HostPtr.vmctx();
    println!("#define VMCTX_OFF_MAGIC {}u", stat.magic());
    println!("#define VMCTX_OFF_STORE_CONTEXT {}u", stat.store_context());
    println!("#define VMCTX_OFF_BUILTIN_FUNCTIONS {}u", stat.builtin_functions());
    println!("#define VMCTX_OFF_EPOCH_PTR {}u", stat.epoch_ptr());
    println!("#define VMCTX_OFF_GC_HEAP_DATA {}u", stat.gc_heap_data());
    println!("#define VMCTX_OFF_TYPE_IDS {}u", stat.type_ids());
    println!("#define VMCTX_OFF_END_OF_STATIC_FIELDS {}u", stat.end_of_static_fields());
    println!();
    // Dynamic fields of VMContext.
    println!("#define VMCTX_OFF_IMPORTED_MEMORIES {}u", vm.imported_memories().begin());
    println!("#define VMCTX_OFF_MEMORIES {}u", vm.memories().begin());
    println!("#define VMCTX_OFF_OWNED_MEMORIES {}u", vm.owned_memories().begin());
    println!("#define VMCTX_OFF_IMPORTED_FUNCTIONS {}u", vm.imported_functions().begin());
    println!("#define VMCTX_OFF_IMPORTED_TABLES {}u", vm.imported_tables().begin());
    println!("#define VMCTX_OFF_IMPORTED_GLOBALS {}u", vm.imported_globals().begin());
    println!("#define VMCTX_OFF_IMPORTED_TAGS {}u", vm.imported_tags().begin());
    println!("#define VMCTX_OFF_TABLES {}u", vm.tables().begin());
    println!("#define VMCTX_OFF_GLOBALS {}", vm.globals().begin());
    println!("#define VMCTX_OFF_TAGS {}u", vm.tags().begin());
    println!("#define VMCTX_OFF_FUNC_REFS {}u", vm.func_refs().begin());
    println!("#define VMCTX_OFF_STARTUP_FUNC_REF {}u", vm.startup_func_ref());
    println!("#define VMCTX_OFF_RUNTIME_DATA_BASES {}u", vm.runtime_data_bases().begin());
    println!("#define VMCTX_OFF_RUNTIME_DATA_LENGTHS {}u", vm.runtime_data_lengths().begin());
    println!();
    // VMStoreContext fields.
    println!("#define VMSTORE_OFF_FUEL_CONSUMED {}u", sc.fuel_consumed());
    println!("#define VMSTORE_OFF_EPOCH_DEADLINE {}u", sc.epoch_deadline());
    println!("#define VMSTORE_OFF_EXECUTION_VERSION {}u", sc.execution_version());
    println!("#define VMSTORE_OFF_STACK_LIMIT {}u", sc.stack_limit());
    println!("#define VMSTORE_OFF_GC_HEAP {}u", sc.gc_heap());
    println!("#define VMSTORE_OFF_GC_HEAP_BASE {}u", sc.gc_heap_base());
    println!("#define VMSTORE_OFF_GC_HEAP_CURRENT_LENGTH {}u", sc.gc_heap_current_length());
    println!("#define VMSTORE_OFF_LAST_WASM_EXIT_TRAMPOLINE_FP {}u", sc.last_wasm_exit_trampoline_fp());
    println!("#define VMSTORE_OFF_LAST_WASM_EXIT_PC {}u", sc.last_wasm_exit_pc());
    println!("#define VMSTORE_OFF_LAST_WASM_ENTRY_SP {}u", sc.last_wasm_entry_sp());
    println!("#define VMSTORE_OFF_LAST_WASM_ENTRY_FP {}u", sc.last_wasm_entry_fp());
    println!("#define VMSTORE_OFF_LAST_WASM_ENTRY_TRAP_HANDLER {}u", sc.last_wasm_entry_trap_handler());
    println!("#define VMSTORE_OFF_STACK_CHAIN {}u", sc.stack_chain());
    println!("#define VMSTORE_OFF_STORE_DATA {}u", sc.store_data());
    println!("#define VMSTORE_OFF_ASYNC_GUARD_RANGE {}u", sc.async_guard_range());
    println!("#define VMSTORE_OFF_COMPONENT_CONTEXT {}u", sc.component_context());
    println!("#define VMSTORE_OFF_CURRENT_THREAD {}u", sc.current_thread());
    println!("#define VMSTORE_SIZE {}u", sc.size());
    println!();
    // Arrays / structs.
    println!("#define VM_FUNCTION_IMPORT_SIZE {}u", fi.size());
    println!("#define VM_FUNCTION_IMPORT_OFF_ARRAY_CALL {}u", fi.array_call());
    println!("#define VM_FUNCTION_IMPORT_OFF_WASM_CALL {}u", fi.wasm_call());
    println!("#define VM_FUNCTION_IMPORT_OFF_TYPE_INDEX {}u", fi.type_index());
    println!("#define VM_FUNCTION_IMPORT_OFF_VMCTX {}u", fi.vmctx());
    println!("#define VM_MEMORY_DEFINITION_SIZE {}u", md.size());
    println!("#define VM_MEMORY_DEFINITION_OFF_BASE {}u", md.base());
    println!("#define VM_MEMORY_DEFINITION_OFF_CURRENT_LENGTH {}u", md.current_length());
    println!("#define VM_TABLE_DEFINITION_SIZE {}u", td.size());
    println!("#define VM_TABLE_DEFINITION_OFF_BASE {}u", td.base());
    println!("#define VM_TABLE_DEFINITION_OFF_CURRENT_ELEMENTS {}u", td.current_elements());
    println!("#define VM_FUNC_REF_SIZE {}u", fr.size());
    println!("#define VM_FUNC_REF_OFF_ARRAY_CALL {}u", fr.array_call());
    println!("#define VM_FUNC_REF_OFF_WASM_CALL {}u", fr.wasm_call());
    println!("#define VM_FUNC_REF_OFF_TYPE_INDEX {}u", fr.type_index());
    println!("#define VM_FUNC_REF_OFF_VMCTX {}u", fr.vmctx());
    println!();
    // Builtin indices used by this module (the only trampolines present in
    // out.full.o). Their offsets in the builtins array are index * 8.
    for (name, idx) in [
        ("MEMORY_COPY", BuiltinFunctionIndex::memory_copy()),
        ("MEMORY_FILL", BuiltinFunctionIndex::memory_fill()),
        ("MEMORY_ATOMIC_NOTIFY", BuiltinFunctionIndex::memory_atomic_notify()),
        ("MEMORY_ATOMIC_WAIT32", BuiltinFunctionIndex::memory_atomic_wait32()),
        ("THROW_REF", BuiltinFunctionIndex::throw_ref()),
        ("TABLE_GET_LAZY_INIT_FUNC_REF", BuiltinFunctionIndex::table_get_lazy_init_func_ref()),
        ("GC_ALLOC_RAW", BuiltinFunctionIndex::gc_alloc_raw()),
        ("GET_INSTANCE_ID", BuiltinFunctionIndex::get_instance_id()),
    ] {
        println!("#define BUILTIN_INDEX_{name} {}u", idx.index());
    }
    println!("#define BUILTIN_FUNCTIONS_ARRAY_LEN {}u", BuiltinFunctionIndex::len());
    println!();
    for (i, mem) in module.memories.iter() {
        println!(
            "// memory {i:?}: min={} max={:?} shared={} page_size_log2={}",
            mem.limits.min, mem.limits.max, mem.shared, mem.page_size_log2
        );
    }
    for (i, table) in module.tables.iter() {
        println!(
            "// table {i:?}: min={} max={:?} wasm_ty={:?}",
            table.limits.min, table.limits.max, table.ref_type
        );
    }
    for (name, kind) in module.exports.iter() {
        if let wasmtime_environ::EntityIndex::Function(fi) = kind {
            let defined = fi.as_u32().wrapping_sub(module.num_imported_funcs as u32);
            println!("// export {name:?} func_index={} defined_index={defined}", fi.as_u32());
        }
    }
    Ok(())
}
