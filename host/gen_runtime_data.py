#!/usr/bin/env python3
"""Emit host/runtime_data.{h,cpp} from the wasm data section.

Wasmtime stores one "runtime data" base/length pair per (passive or active)
data segment at the end of VMContext.  tools/wasm2obj does not emit those
images into the ELF, so the native host has to supply them itself.  Segment 0
of this module is the TLS initialisation image used by __wasm_init_tls.
"""
import argparse
import pathlib


def uleb(buf, pos):
    val = shift = 0
    while True:
        b = buf[pos]
        pos += 1
        val |= (b & 0x7F) << shift
        if not b & 0x80:
            return val, pos
        shift += 7


def parse_segments(wasm):
    buf = pathlib.Path(wasm).read_bytes()
    if buf[:4] != b"\0asm":
        raise SystemExit("not a wasm file")
    pos = 8
    while pos < len(buf):
        sid = buf[pos]
        pos += 1
        size, pos = uleb(buf, pos)
        end = pos + size
        if sid == 11:  # data section
            count, pos = uleb(buf, pos)
            segs = []
            segs = []
            for _ in range(count):
                flags, pos = uleb(buf, pos)
                dest = 0xFFFFFFFF  # passive: TLS / table init, not linear memory
                if flags == 0:
                    dest, pos = uleb(buf, pos)
                    n, pos = uleb(buf, pos)
                elif flags == 1:
                    n, pos = uleb(buf, pos)
                elif flags == 2:
                    _, pos = uleb(buf, pos)  # memory index
                    dest, pos = uleb(buf, pos)
                    n, pos = uleb(buf, pos)
                else:
                    raise SystemExit(f"bad data segment flags {flags}")
                segs.append((buf[pos:pos + n], dest))
                pos += n
            return segs
        pos = end
    raise SystemExit("no data section")


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--wasm", default="/tmp/opencode/WebClient.raknet.wasm")
    ap.add_argument("--out-dir", default=pathlib.Path(__file__).resolve().parent)
    args = ap.parse_args()
    segs = parse_segments(args.wasm)
    out = pathlib.Path(args.out_dir)

    (out / "runtime_data.h").write_text(
        "// Generated by host/gen_runtime_data.py -- data segment images.\n"
        "#pragma once\n#include <cstdint>\n\n"
        f"#define WB_RUNTIME_DATA_COUNT {len(segs)}u\n"
        "extern const unsigned char wb_runtime_data[];\n"
        "extern const uint32_t wb_runtime_data_offsets[WB_RUNTIME_DATA_COUNT];\n"
        "extern const uint32_t wb_runtime_data_lengths[WB_RUNTIME_DATA_COUNT];\n"
        "// 0xffffffff for passive segments (TLS image / table init).\n"
        "extern const uint32_t wb_runtime_data_dests[WB_RUNTIME_DATA_COUNT];\n"
    )

    blob = bytearray()
    offsets, lengths, dests = [], [], []
    for seg, dest in segs:
        offsets.append(len(blob))
        lengths.append(len(seg))
        dests.append(dest)
        blob.extend(seg)

    lines = [
        "// Generated by host/gen_runtime_data.py -- DO NOT EDIT BY HAND.\n",
        '#include "runtime_data.h"\n\n',
        "const unsigned char wb_runtime_data[] = {\n",
    ]
    for i in range(0, len(blob), 32):
        chunk = blob[i:i + 32]
        lines.append("  " + ",".join(str(b) for b in chunk) + ",\n")
    lines.append("};\n\n")
    lines.append("const uint32_t wb_runtime_data_offsets[WB_RUNTIME_DATA_COUNT] = {\n")
    for i in range(0, len(offsets), 16):
        lines.append("  " + ",".join(str(x) for x in offsets[i:i + 16]) + ",\n")
    lines.append("};\n\n")
    lines.append("const uint32_t wb_runtime_data_lengths[WB_RUNTIME_DATA_COUNT] = {\n")
    for i in range(0, len(lengths), 16):
        lines.append("  " + ",".join(str(x) for x in lengths[i:i + 16]) + ",\n")
    lines.append("};\n\n")
    lines.append("const uint32_t wb_runtime_data_dests[WB_RUNTIME_DATA_COUNT] = {\n")
    for i in range(0, len(dests), 16):
        lines.append("  " + ",".join(str(x) for x in dests[i:i + 16]) + ",\n")
    lines.append("};\n")
    (out / "runtime_data.cpp").write_text("".join(lines))
    print(f"generated {len(segs)} data segments ({len(blob)} bytes)")


if __name__ == "__main__":
    main()
