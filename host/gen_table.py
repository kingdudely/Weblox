#!/usr/bin/env python3
"""Generate host/table.{h,cpp} from the wasm table + element sections.

Wasmtime never puts the element segment into the compiled ELF: at instantiation
it turns every active element into a ``VMFuncRef`` pointing at the defined
function's wasm-call entry (or an import's wasm-call trampoline) with the
function's wasm type index.  A plain C++ host has to do that itself.

Only ``table.h`` is checked in; ``table.cpp`` is a build artefact regenerated by
the Makefile (it contains one extern declaration / pointer initializer per
table entry and is therefore far too large for git).

Usage:
    python3 gen_table.py [--wasm PATH] [--out-dir DIR]
"""
import argparse
import pathlib


def uleb(buf, pos):
    val = shift = 0
    while True:
        b = buf[pos]
        pos += 1
        val |= (b & 0x7F) << shift
        if not b & 0x80:
            return val, pos
        shift += 7


def sleb(buf, pos):
    val = shift = 0
    while True:
        b = buf[pos]
        pos += 1
        val |= (b & 0x7F) << shift
        shift += 7
        if not b & 0x80:
            if shift < 32 and b & 0x40:
                val -= 1 << shift
            return val & 0xFFFFFFFF, pos


def sections(buf):
    if buf[:4] != b"\0asm":
        raise SystemExit("not a wasm module")
    pos = 8
    while pos < len(buf):
        sid = buf[pos]
        pos += 1
        size, pos = uleb(buf, pos)
        yield sid, pos, size
        pos += size


def parse_imports(buf):
    """Return (number of imported funcs, [wasm type index per import])."""
    for sid, start, size in sections(buf):
        if sid != 2:
            continue
        count, p = uleb(buf, start)
        types = []
        for _ in range(count):
            n, p = uleb(buf, p)
            p += n
            n, p = uleb(buf, p)
            p += n
            kind = buf[p]
            p += 1
            if kind == 0:  # func
                t, p = uleb(buf, p)
                types.append(t)
            elif kind == 1:  # table: reftype + limits
                p += 1
                flags = buf[p]
                p += 1
                _, p = uleb(buf, p)
                if flags & 1:
                    _, p = uleb(buf, p)
            elif kind == 2:  # memory: limits
                flags = buf[p]
                p += 1
                _, p = uleb(buf, p)
                if flags & 1:
                    _, p = uleb(buf, p)
            elif kind == 3:  # global: valtype + mutability
                p += 2
            elif kind == 4:  # tag: attribute + type index
                p += 1
                _, p = uleb(buf, p)
            else:
                raise SystemExit(f"unsupported import kind {kind}")
        return len(types), types
    raise SystemExit("no import section")


def parse_module(buf):
    n_imported, import_types = parse_imports(buf)
    func_types = list(import_types)
    n_types = 0
    table_size = None
    entries = []  # (table_index, func_index)

    for sid, start, size in sections(buf):
        end = start + size
        if sid == 1:  # type section
            n_types, _ = uleb(buf, start)
        elif sid == 3:  # function section
            count, p = uleb(buf, start)
            for _ in range(count):
                t, p = uleb(buf, p)
                func_types.append(t)
        elif sid == 4:  # table section
            count, p = uleb(buf, start)
            if count != 1:
                raise SystemExit(f"expected one table, found {count}")
            elemtype = buf[p]
            p += 1
            if elemtype != 0x70:
                raise SystemExit(f"expected funcref table, got {elemtype:#x}")
            flags = buf[p]
            p += 1
            table_size, p = uleb(buf, p)
            if flags & 1:
                _, p = uleb(buf, p)
        elif sid == 9:  # element section
            count, p = uleb(buf, start)
            for _ in range(count):
                flags, p = uleb(buf, p)
                table_index = 0
                offset = None
                if flags in (0, 4):  # active, implicit table 0
                    if buf[p] != 0x41:
                        raise SystemExit(f"bad elem offset opcode {buf[p]:#x}")
                    offset, p = sleb(buf, p + 1)
                    if buf[p] != 0x0B:
                        raise SystemExit("unterminated elem offset")
                    p += 1
                elif flags in (2, 6):  # active, explicit table
                    table_index, p = uleb(buf, p)
                    if buf[p] != 0x41:
                        raise SystemExit(f"bad elem offset opcode {buf[p]:#x}")
                    offset, p = sleb(buf, p + 1)
                    if buf[p] != 0x0B:
                        raise SystemExit("unterminated elem offset")
                    p += 1
                elif flags in (1, 3, 5, 7):  # passive / declarative: not installed
                    if flags in (1, 3):
                        p += 1  # elemkind
                    n, p = uleb(buf, p)
                    for _ in range(n):
                        if flags in (5, 7):  # vec(elemexpr): ref.func N; end
                            if buf[p] != 0xD2:
                                raise SystemExit(f"bad elem expr opcode {buf[p]:#x}")
                            _, p = uleb(buf, p + 1)
                            p += 1  # end
                        else:
                            _, p = uleb(buf, p)
                    continue
                else:
                    raise SystemExit(f"unsupported element segment flags {flags}")
                if table_index != 0:
                    raise SystemExit("table indices other than 0 are unsupported")
                if flags == 2:  # active with explicit table: elemkind byte
                    p += 1
                n, p = uleb(buf, p)
                expr = flags in (4, 6)
                for k in range(n):
                    if expr:
                        if buf[p] != 0xD2:
                            raise SystemExit(f"bad elem expr opcode {buf[p]:#x}")
                        func, p = uleb(buf, p + 1)
                        p += 1  # end
                    else:
                        func, p = uleb(buf, p)
                    entries.append((offset + k, func))
                if p > end:
                    raise SystemExit("element section overrun")
            if p != end:
                raise SystemExit(f"element section trailing bytes: {end - p}")

    if table_size is None:
        raise SystemExit("no table section")
    if n_types == 0:
        raise SystemExit("no type section")
    for ti, fi in entries:
        if ti >= table_size:
            raise SystemExit(f"element index {ti} outside table of {table_size}")
        if fi >= len(func_types):
            raise SystemExit(f"element func index {fi} outside {len(func_types)} funcs")
    return table_size, n_imported, func_types, entries


HEADER = """// Generated by host/gen_table.py from the wasm element section -- DO NOT EDIT.
#pragma once

#include <cstdint>

// One active element segment entry.  `wasm_call` is null for imported
// functions: vmctx.cpp resolves those through wb::import_wasm_call(func_index+1).
struct WBTableEntry {
  std::uint32_t table_index;
  std::uint32_t func_index;
  std::uint32_t type_index;
  void* wasm_call;
};

extern const std::uint32_t wb_table_size;        // table min == max
extern const std::uint32_t wb_table_init_count;  // active elements initialized
extern const WBTableEntry wb_table_init[];
"""


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--wasm", default="/tmp/opencode/WebClient.raknet.wasm")
    ap.add_argument("--out-dir", default=pathlib.Path(__file__).resolve().parent)
    args = ap.parse_args()

    buf = pathlib.Path(args.wasm).read_bytes()
    table_size, n_imported, func_types, entries = parse_module(buf)
    out = pathlib.Path(args.out_dir)

    (out / "table.h").write_text(HEADER)

    lines = [
        "// Generated by host/gen_table.py -- DO NOT EDIT BY HAND.\n",
        '#include "table.h"\n\n',
        f"const std::uint32_t wb_table_size = {table_size}u;\n",
        f"const std::uint32_t wb_table_init_count = {len(entries)}u;\n\n",
        "namespace {\n",
    ]
    defined = sorted({fi - n_imported for _, fi in entries if fi >= n_imported})
    for n in defined:
        lines.append(f"extern \"C\" void _wasm_function_{n}(void*, void*);\n")
    lines.append("}  // namespace\n\n")
    lines.append("const WBTableEntry wb_table_init[] = {\n")
    for ti, fi in entries:
        ty = func_types[fi]
        if fi < n_imported:
            call = "nullptr"  # resolved at runtime from wb::import_wasm_call()
        else:
            call = f"reinterpret_cast<void*>(&_wasm_function_{fi - n_imported})"
        lines.append(f"  {{{ti}u, {fi}u, {ty}u, {call}}},\n")
    lines.append("};\n")
    (out / "table.cpp").write_text("".join(lines))

    imports = sum(1 for _, fi in entries if fi < n_imported)
    print(f"table: declared={table_size} initialized={len(entries)} "
          f"imports={imports} defined={len(entries) - imports} "
          f"distinct_defined={len(defined)} first_defined_func={n_imported}")


if __name__ == "__main__":
    main()
