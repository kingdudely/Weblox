#!/usr/bin/env python3
"""Generate pass-through forwarders for the gl* imports.

Specials (query/creation calls that need a fallback when GL is absent) live in
impl/gl_special.c and are skipped here.
"""
import re

MANUAL = {
    'glGetString', 'glGetStringi', 'glGetIntegerv', 'glGetError',
    'glCreateShader', 'glCreateProgram', 'glGetUniformLocation',
    'glGetActiveUniform', 'glGetShaderiv', 'glGetProgramiv',
    'glGetShaderInfoLog', 'glGetProgramInfoLog', 'glGetUniformBlockIndex',
    'glCheckFramebufferStatus', 'glClientWaitSync', 'glMapBufferRange', 'glDeleteSync', 'glUnmapBuffer',
    'glShaderSource', 'glUnmapBuffer', 'glGenTextures', 'glGenBuffers', 'glGenFramebuffers',
    'glGenRenderbuffers', 'glGenVertexArrays', 'glFenceSync',
}

# argument positions (1-based, excluding the env receiver) that are guest
# pointers and therefore have to be rebased into linear memory
PTRS = {
    'glBindAttribLocation': (3,),
    'glBufferData': (3,),
    'glBufferSubData': (3,),
    'glClearBufferfv': (2,),
    'glClearBufferiv': (2,),
    'glCompressedTexImage2D': (8,),
    'glCompressedTexImage3D': (9,),
    'glCompressedTexSubImage2D': (9,),
    'glCompressedTexSubImage3D': (11,),
    'glDeleteBuffers': (2,),
    'glDeleteFramebuffers': (2,),
    'glDeleteRenderbuffers': (2,),
    'glDeleteTextures': (2,),
    'glDeleteVertexArrays': (2,),
    'glDrawBuffers': (2,),
    'glGetActiveUniformBlockiv': (4,),
    'glInvalidateFramebuffer': (3,),
    'glReadPixels': (7,),
    'glTexImage2D': (9,),
    'glTexImage3D': (10,),
    'glTexParameterfv': (3,),
    'glTexSubImage2D': (9,),
    'glTexSubImage3D': (10,),
    'glVertexAttribPointer': (6,),
}

decl = re.compile(r'^(u32|u64|f32|f64|void) (w2c_env_(gl\w+))\((.*)\);$')
out = ['/* generated by tools/gen_gl.py - do not edit */',
       '#include "../host/host.h"', '#include "../host/gl.h"', '']
n = 0
cur = None
for line in open('WC.h'):
    m = re.match(r"^/\* import: 'env' '(gl\w+)' \*/$", line.strip())
    if m:
        cur = m.group(1)
        continue
    d = decl.match(line.strip())
    if not d or not cur:
        continue
    ret, fn, args = d.group(1), d.group(2), d.group(4)
    if cur in MANUAL:
        cur = None
        continue
    raw = [a.strip() for a in args.split(',')] if args.strip() else []
    names = [f'a{i}' for i in range(len(raw))]
    sig = ', '.join(f'{r}{" " if not r.endswith("*") else ""}{n2}' for r, n2 in zip(raw, names))
    gr = raw[1:]; gn = names[1:]
    argt = ', '.join(gr)
    proc = 'p_' + cur
    zero = {'u32': '0', 'u64': '0', 'f32': '0.0f', 'f64': '0.0', 'void': None}[ret]
    out.append(f'static void* {proc};')
    out.append(f'__attribute__((weak)) {ret} wc_impl_{cur}({sig}) {{')
    out.append(f'  if (!{proc}) {proc} = wc_gl_proc("{cur}");')
    out.append(f'  if (!{proc}) {{ wc_gl_miss("{cur}");' + (f' return {zero};' if zero else ' return;') + ' }')
    ptrs = PTRS.get(cur, ())
    gv = [f'(u32)(uintptr_t)wc_ptr({n2})' if (i + 1) in ptrs and r == 'u32' else n2
          for i, (r, n2) in enumerate(zip(gr, gn))]
    call = f'(({ret} (*)({argt})){proc})({", ".join(gv)})'
    out.append(f'  {"return " if zero else ""}{call};')
    out.append('}')
    out.append('')
    n += 1
    cur = None
open('impl/gl_auto.c', 'w').write('\n'.join(out))
print(f'gl_auto.c: {n} forwarders')
