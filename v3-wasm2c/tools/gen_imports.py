#!/usr/bin/env python3
"""Generate a stub import table (spike) from WC.h."""
import re

# imports implemented by hand live in src/imports/*.rs; everything else is
# stubbed here so the module always links and the real ones can land one by one
SKIP = {n.strip() for n in open('/home/john/Alcohol/tools/implemented.txt') if n.strip()}

src = open('/home/john/Alcohol/WC.h').read()
TY = {'u32': 'i32', 'u64': 'i64', 'f32': 'f32', 'f64': 'f64'}
ZERO = {'void': '()', 'u32': '0', 'u64': '0', 'f32': '0.0', 'f64': '0.0'}

pat = re.compile(
    r"/\* import: '([a-z_0-9]+)' '([^']+)' \*/\s*\n([a-z0-9_]+) (w2c_\w+)\(([^)]*)\);"
)

head = '''// generated by tools/gen_imports.py - do not edit
use crate::state::St;
use anyhow::Result;
use wasmtime::{Caller, Linker};

fn ty(t: &str) -> &'static str {
    match t { "u32" => "i32", "u64" => "i64", "f32" => "f32", "f64" => "f64", _ => "i32" }
}
fn zero(t: &str) -> &'static str {
    match t { "void" => "", "u32" => "0", "u64" => "0", "f32" => "0.0", "f64" => "0.0", _ => "0" }
}

pub fn register(l: &mut Linker<St>) -> Result<()> {
'''

out = [head]
n = nasync = 0
for m in pat.finditer(src):
    module, name, ret, _fn, args = m.groups()
    if name in SKIP:
        continue
    types = [a.strip() for a in args.split(',')][1:]
    ptys = ', '.join(TY[t] for t in types)
    curried = ''.join(', a%d: %s' % (i, TY[t]) for i, t in enumerate(types))
    tupled = ', _a: (%s%s)' % (ptys, ',' if len(types) == 1 else '')
    z = ZERO[ret]
    rt = TY.get(ret, '()')
    is_async = name == 'js_fetch_file' or name.startswith('invoke_') or name.startswith('__asyncjs__')
    if is_async:
        nasync += 1
        out.append('    l.func_wrap_async("%s", "%s", |_c: Caller<\'_, St>%s| { crate::trace::hit("%s"); Box::new(async move { Ok(%s) }) })?;\n'
                   % (module, name, tupled, name, z))
    else:
        out.append('    l.func_wrap("%s", "%s", |_c: Caller<\'_, St>%s| -> %s { crate::trace::hit("%s"); %s })?;\n'
                   % (module, name, curried, rt, name, z))
    n += 1
out.append('    Ok(())\n}\n')
open('/home/john/Alcohol/host-rs/src/imports/stubs.rs', 'w').write(''.join(out))
print('imports', n, 'async', nasync)
