#!/usr/bin/env python3
"""Generate src/imports/stubs.rs from the module's import section (wat form).

Everything not implemented by hand (SKIP) gets a correctly typed zero stub so
the module links; the real ones land one at a time.
"""
import re
import sys

WAT = sys.argv[1]
OUT = sys.argv[2]
SKIP = set(open(sys.argv[3]).read().split()) if len(sys.argv) > 3 else set()

IQ = re.compile(r'^  \(import "([^"]+)" "([^"]+)" \(func \(;\d+;\) \(type \d+\)((?: \(param [^)]*\))*)((?: \(result [^)]*\))*)\)\)$')

rows = []
for line in open(WAT, encoding="utf-8"):
    m = IQ.match(line.rstrip("\n"))
    if not m:
        continue
    mod, name, params, res = m.groups()
    if name in SKIP:
        continue
    ps = " ".join(re.findall(r"\(param ([^)]*)\)", params)).split()
    rs = " ".join(re.findall(r"\(result ([^)]*)\)", res)).split()
    rows.append((mod, name, ps, rs))

T = {"i32": "i32", "i64": "i64", "f32": "f32", "f64": "f64"}
Z = {"i32": "0", "i64": "0", "f32": "0.0", "f64": "0.0"}
ASYNC = re.compile(r"^__asyncjs__")

out = [
    "// generated by tools/gen_imports.py - do not edit",
    "use crate::state::St;",
    "use anyhow::Result;",
    "use wasmtime::{Caller, Linker};",
    "",
    "pub fn register(l: &mut Linker<St>) -> Result<()> {",
]
for mod, name, ps, rs in rows:
    ts = [T[p] for p in ps]
    res = rs[0] if rs else None
    zero = "" if res is None else Z[res]
    ret = "" if res is None else f" -> {T[res]}"
    args = ", ".join(f"a{i}: {t}" for i, t in enumerate(ts))
    if args:
        args += ", "
    out.append(
        f'    l.func_wrap("{mod}", "{name}", '
        f"|_c: Caller<'_, St>, {args}|{ret} {{ crate::trace::hit(\"{name}\"); {zero} }})?;"
    )
out += ["    Ok(())", "}"]
open(OUT, "w").write("\n".join(out) + "\n")
print(f"{len(rows)} stubs -> {OUT}")
